#!/usr/bin/env node
// Generates the pet-care art: the food & water bowl and litter box furniture
// (PNG + manifest) and the webview sprite pack (bowl fill states, litter
// states, poop, request bubbles, hearts, radial menu icons, effects).
//
//   node scripts/generate-pet-care-sprites.mjs
//
// Edit scripts/petCare/art.mjs, not the outputs. The art is MIT like the
// rest of the repo. Cat care poses (eat, drink, poop, petted, play) are not
// here: the webview derives them from each cat's own sheet at runtime
// (webview-ui/src/office/sprites/petCareFrames.ts), so custom cats get them too.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { PNG } from 'pngjs';
import * as prettier from 'prettier';

import {
  BOWL_COMBO,
  DISH,
  FOOD_FILL,
  HAND,
  HEART,
  ICONS,
  LITTER,
  PALETTE,
  POOP,
  requestBubble,
  SPARKLE,
  STINK,
  WATER_FILL,
  YARN,
} from './petCare/art.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const furnitureDir = path.join(root, 'webview-ui', 'public', 'assets', 'furniture');
const spritePack = path.join(root, 'webview-ui', 'src', 'office', 'sprites', 'petCareSprites.json');

/** Bowl combo with food level `f` and water level `w` (0..3 each). */
function bowl(f, w) {
  return BOWL_COMBO.map((row) =>
    [...row]
      .map((ch, x) => {
        if (!'123'.includes(ch)) return ch;
        const fill = x < 8 ? FOOD_FILL[f][ch] : WATER_FILL[w][ch];
        return fill[(x < 8 ? x - 2 : x - 10) % 4];
      })
      .join(''),
  );
}

function hex(color) {
  const v = parseInt(color.slice(1), 16);
  return [(v >> 16) & 255, (v >> 8) & 255, v & 255];
}

function writePng(file, rows) {
  const png = new PNG({ width: rows[0].length, height: rows.length });
  rows.forEach((row, y) =>
    [...row].forEach((ch, x) => {
      const i = (y * png.width + x) * 4;
      if (ch === '.') return;
      const color = PALETTE[ch];
      if (!color) throw new Error(`No palette color for '${ch}'`);
      const [r, g, b] = hex(color);
      png.data.set([r, g, b, 255], i);
    }),
  );
  fs.writeFileSync(file, PNG.sync.write(png));
}

function writeFurniture(id, name, rows, extra) {
  const dir = path.join(furnitureDir, id);
  fs.mkdirSync(dir, { recursive: true });
  writePng(path.join(dir, `${id}.png`), rows);
  const manifest = {
    id,
    name,
    category: 'misc',
    type: 'asset',
    canPlaceOnWalls: false,
    canPlaceOnSurfaces: false,
    backgroundTiles: 0,
    width: rows[0].length,
    height: rows.length,
    footprintW: 1,
    footprintH: 1,
    ...extra,
  };
  fs.writeFileSync(path.join(dir, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
}

// Furniture: the catalog sprite is the full bowl / the clean box. The
// webview swaps in the fill-state sprites below at render time.
writeFurniture('PET_BOWL', 'Food & water bowl', bowl(3, 3));
// The cat steps INTO the box, so its tile stays walkable (backgroundTiles).
writeFurniture('LITTER_BOX', 'Litter box', LITTER[0], { backgroundTiles: 1 });

const pack = {
  description: 'Generated by scripts/generate-pet-care-sprites.mjs. Do not edit by hand.',
  palette: PALETTE,
  sprites: {
    bowl: [0, 1, 2, 3].map((f) => [0, 1, 2, 3].map((w) => bowl(f, w))),
    litter: LITTER,
    poop: POOP,
    stink: STINK,
    requests: Object.fromEntries(
      ['food', 'water', 'scratch', 'play', 'litter'].map((k) => [k, requestBubble(k)]),
    ),
    icons: ICONS,
    heart: HEART,
    sparkle: SPARKLE,
    hand: HAND,
    yarn: YARN,
    dish: DISH,
  },
};
// Format like lint-staged would, so a regenerate is a no-op diff.
const options = (await prettier.resolveConfig(spritePack)) ?? {};
fs.writeFileSync(
  spritePack,
  await prettier.format(JSON.stringify(pack), { ...options, parser: 'json' }),
);

console.log('Wrote PET_BOWL, LITTER_BOX furniture and', path.relative(root, spritePack));
